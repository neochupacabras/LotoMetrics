SELECT json_build_object(
 'freq',(SELECT json_agg(t) FROM fn_frequencia(2,NULL) t),
 'freq100',(SELECT json_agg(t) FROM fn_frequencia(2,100) t),
 'atraso',(SELECT json_agg(t) FROM fn_atraso(2) t),
 'maior_atraso',(SELECT json_agg(t) FROM fn_maior_atraso_historico(2) t),
 'ciclo_atual',(SELECT json_agg(t) FROM fn_ciclo_atual(2) t),
 'ciclos',(SELECT json_agg(t) FROM fn_ciclos_historico(2) t),
 'seq',(SELECT json_agg(t) FROM fn_distribuicao_sequencias(2) t),
 'seq_dezena',(SELECT json_agg(t) FROM fn_maior_sequencia_consecutiva_dezena(2) t),
 'parimpar',(SELECT json_agg(t) FROM fn_distribuicao_par_impar(2) t),
 'primos_f',(SELECT json_agg(t) FROM fn_primos_frequencia(2) t),
 'primos_d',(SELECT json_agg(t) FROM fn_primos_distribuicao(2) t),
 'fib_f',(SELECT json_agg(t) FROM fn_fibonacci_frequencia(2) t),
 'fib_d',(SELECT json_agg(t) FROM fn_fibonacci_distribuicao(2) t),
 'm3_f',(SELECT json_agg(t) FROM fn_multiplos_3_frequencia(2) t),
 'm3_d',(SELECT json_agg(t) FROM fn_multiplos_3_distribuicao(2) t),
 'soma',(SELECT json_agg(t) FROM fn_estatisticas_soma(2) t),
 'hist',(SELECT json_agg(t) FROM fn_histograma_soma(2,10) t),
 'rep',(SELECT json_agg(t) FROM fn_distribuicao_repetidas(2) t),
 'mc_f',(SELECT json_agg(t) FROM fn_moldura_centro_frequencia(2) t),
 'mc_d',(SELECT json_agg(t) FROM fn_distribuicao_moldura_centro(2) t),
 'lin',(SELECT json_agg(t) FROM fn_frequencia_por_linha(2) t),
 'col',(SELECT json_agg(t) FROM fn_frequencia_por_coluna(2) t),
 'duques',(SELECT json_agg(t) FROM fn_duques_mais_frequentes(2,400) t),
 'trincas',(SELECT json_agg(t) FROM fn_trincas_mais_frequentes(2,30) t),
 'trincas_n',(SELECT count(*) FROM fn_trincas_mais_frequentes(2,10000000) t),
 'defs',(SELECT json_agg(json_build_object('n',p.proname,'md5',md5(pg_get_functiondef(p.oid)),'def',pg_get_functiondef(p.oid))) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.proname LIKE 'fn\_%')
) AS r;
